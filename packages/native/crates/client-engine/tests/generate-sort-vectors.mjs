#!/usr/bin/env node
// Writes sort-vectors.tsv: `Array.prototype.sort` with a comparator, as the
// JavaScript engine running this script does it, on seeded arrays of small
// integers under comparators of five kinds, so the Rust port of V8's
// TimSort (src/js/sort.rs) is held to V8's result call for call
// (tests/sort_vectors.rs). Run it under Electron's Node (V8, the product's
// renderer):
//
//   ELECTRON_RUN_AS_NODE=1 <electron binary> generate-sort-vectors.mjs [--check] [--engine-label=<text>]
//
// `--check` compares with the tracked file instead of writing it (exit 1 on a
// difference). Under Bun (JavaScriptCore) `--check` lists where that engine
// sorts otherwise (docs/TESTING.md, "Engine differences"). Deterministic: no
// clock, no Math.random; the comparators are a 32-bit hash of the seed and the
// two elements, the same in the Rust test.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FILE = path.join(HERE, 'sort-vectors.tsv');

/** A 32-bit mix of three integers (the Rust test has the same). */
export function mix(seed, a, b) {
  let h = Math.imul(seed ^ 0x9e3779b9, 0x85ebca6b) >>> 0;
  h = Math.imul(h ^ Math.imul(a + 0x632be5ab, 0xc2b2ae35), 0x27d4eb2f) >>> 0;
  h = Math.imul(h ^ Math.imul(b + 0x165667b1, 0x9e3779b1), 0x85ebca6b) >>> 0;
  return (h ^ (h >>> 15)) >>> 0;
}

/**
 * The comparators: `consistent` (by value), `ties` (by value / 4: many equal
 * keys, stability shows), `random` (each pair answers -1, 0 or 1 at random,
 * not even antisymmetric), `antisymmetric` (random but compare(a, b) = -compare(b, a)),
 * `nan` (by value, except NaN for pairs the hash picks, which counts as 0).
 */
export const KINDS = ['consistent', 'ties', 'random', 'antisymmetric', 'nan'];
export function comparator(kind, seed) {
  switch (kind) {
    case 'consistent': return (a, b) => a - b;
    case 'ties': return (a, b) => (a >> 2) - (b >> 2);
    case 'random': return (a, b) => (mix(seed, a, b) % 3) - 1;
    case 'antisymmetric': return (a, b) => (a === b ? 0 : a < b ? (mix(seed, a, b) % 3) - 1 : -((mix(seed, b, a) % 3) - 1));
    case 'nan': return (a, b) => (mix(seed, a, b) % 5 === 0 ? NaN : a - b);
    default: throw new Error(kind);
  }
}

/** The seeded input of a row: its length, and values in [0, range), with runs (ascending, descending) to make TimSort gallop. */
export function input(seed) {
  const length = [0, 1, 2, 3, 7, 31, 32, 33, 63, 64, 65, 100, 128, 200, 257, 400][seed % 16];
  const range = [2, 5, 16, 64, 1000][mix(seed, 1, 2) % 5];
  const out = [];
  let state = mix(seed, 3, 4);
  while (out.length < length) {
    state = mix(state, out.length, 5);
    const shape = state % 4;
    const run = 1 + (state >>> 8) % 40;
    const start = (state >>> 16) % range;
    for (let at = 0; at < run && out.length < length; at += 1) {
      out.push(shape === 0 ? (start + at) % range : shape === 1 ? (range + start - at) % range : mix(state, at, 6) % range);
    }
  }
  return out;
}

const ROWS = 640;
function rows() {
  const lines = [];
  for (let seed = 0; seed < ROWS; seed += 1) {
    const kind = KINDS[seed % KINDS.length];
    const items = input(seed);
    let calls = 0;
    const compare = comparator(kind, seed);
    const sorted = [...items].sort((a, b) => { calls += 1; return compare(a, b); });
    lines.push([seed, kind, items.join(','), sorted.join(','), calls].join('\t'));
  }
  return lines;
}

function main() {
  const argv = process.argv.slice(2);
  const label = argv.find((arg) => arg.startsWith('--engine-label='))?.slice('--engine-label='.length) ?? `V8 ${process.versions.v8 ?? '?'}`;
  const header = `# Generated by generate-sort-vectors.mjs; do not edit. seed, comparator kind, input, ${label.startsWith('V8') ? 'V8' : 'the engine'}'s sorted output, comparator calls.\n`;
  const body = rows();
  if (argv.includes('--check')) {
    const tracked = readFileSync(FILE, 'utf8').split('\n').filter((line) => line && !line.startsWith('#'));
    const differing = body.filter((line, at) => line !== tracked[at]);
    const byKind = {};
    for (const line of differing) { const [, kind, , , ] = line.split('\t'); byKind[kind] = (byKind[kind] ?? 0) + 1; }
    console.log(`${label}: ${body.length - differing.length} of ${body.length} rows as tracked; differing by comparator kind: ${JSON.stringify(byKind)}`);
    const orderDiffers = differing.filter((line) => { const [seed] = line.split('\t'); const other = tracked[Number(seed)]; return line.split('\t')[3] !== other.split('\t')[3]; }).length;
    console.log(`${label}: ${orderDiffers} rows with another order, ${differing.length - orderDiffers} with the same order and another call count`);
    process.exitCode = differing.length ? 1 : 0;
  } else {
    writeFileSync(FILE, header + body.join('\n') + '\n');
    console.log(`wrote ${body.length} rows (${label})`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
