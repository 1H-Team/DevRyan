#!/usr/bin/env node
// Writes config-front-matter.tsv: how the server's two front-matter
// expressions split Markdown files (the agent, command and skill split with
// a body, and the harness skill discovery's), `trim` (the body and the
// written YAML are trimmed), and Node's UTF-8 decoding and encoding of file
// bytes (invalid sequences, overlong forms, encoded surrogates, lone
// surrogates on write). Inputs are the repository's agent and skill files
// and seeded texts with every line ending around the delimiters.
// Command line: config-text-tools.mjs.
import { drawer, isMain, runGenerator } from './config-text-tools.mjs';
import { randomString, repoFixtures } from './config-text-inputs.mjs';

export const FILE = 'config-front-matter.tsv';
export const SEED = 20261116;
export const TRACKED = 500;

const PIECES = ['---', '---', '----', '--', ' ---', '--- ', '\n', '\n', '\r\n', '\r', 'name: x', 'a: 1\nb: 2', '', 'body', '# title', '...', '﻿', ' ', '\t'];
const WHITESPACE = [' ', '\t', '\n', '\r', '\u000b', '\u000c', ' ', ' ', ' ', ' ', ' ', ' ', ' ', ' ', '　', '﻿', '\u0085', '᠎', '​'];
const BYTES = [[0x61], [0xc3, 0xa9], [0xe4, 0xb8, 0xad], [0xf0, 0x9f, 0x98, 0x80], [0x80], [0xbf], [0xc0, 0x80], [0xc1, 0xbf], [0xe0, 0x80, 0x80], [0xed, 0xa0, 0x80], [0xed, 0xbf, 0xbf],
  [0xf4, 0x90, 0x80, 0x80], [0xf5], [0xff], [0xfe], [0xef, 0xbb, 0xbf], [0xe2, 0x82], [0xf0, 0x9f, 0x98], [0xc3], [0x0a], [0x0d]];

export function cases({ count, seed }) {
  const d = drawer(seed);
  const out = [];
  const add = (name, text) => {
    out.push([`${name}-split`, 'front-split', [text]]);
    out.push([`${name}-skill`, 'front-skill', [text]]);
  };
  // The body after the closing delimiter is cut to 120 units: both
  // expressions take it whole or not at all, so more of it checks nothing.
  const cut = (text) => { const close = text.indexOf('\n---', 3); return close < 0 ? text : text.slice(0, close + 4 + 120); };
  for (const [file, text] of repoFixtures()) if (file.endsWith('.md')) { add(`repo-${file}`, cut(text)); add(`repo-crlf-${file}`, cut(text).replace(/\n/g, '\r\n')); }
  const fixed = ['', '---', '---\n', '---\n---', '---\n---\n', '---\n\n---\n', '---\n\n---', '---\nx\n---', '---\nx\n---\n', '---\r\nx\r\n---\r\nbody', '---\nx\r\n---\nbody', '---\rx\r---\r',
    '---\nx\n----\nbody', '---\nx\n--- \nbody', '---\nx\n---\n---\ny\n---\n', '﻿---\nx\n---\n', ' ---\nx\n---\n', '---\nx\n---\r', '---\nx\n---\rbody', '---\nx\r\r\n---\n', '---\nx\n---\n\n\nbody\n'];
  fixed.forEach((text, index) => add(`fixed-${index}`, text));
  for (const ch of WHITESPACE) out.push([`trim-${ch.charCodeAt(0).toString(16)}`, 'trim', [`${ch}x${ch}y${ch}`]]);
  out.push(['trim-all', 'trim', [WHITESPACE.join('')]], ['trim-lone', 'trim', [' \ud800 ']]);
  BYTES.forEach((bytes, index) => out.push([`decode-${index}`, 'utf8-decode', [String.fromCharCode(...bytes, 0x7a, ...bytes)]]));
  out.push(['encode-lone', 'utf8-encode', ['a\ud800b\udc00😀\ud83d']], ['encode-plain', 'utf8-encode', ['é中 ']]);
  while (out.length < count * 2) {
    const index = out.length;
    if (d.chance(0.1)) {
      out.push([`decode-seeded-${index}`, 'utf8-decode', [String.fromCharCode(...d.repeat(1 + d.int(8), () => d.pick(BYTES)).flat())]]);
      continue;
    }
    add(`seeded-${index}`, d.repeat(1 + d.int(8), () => (d.chance(0.8) ? d.pick(PIECES) : randomString(d, 6))).join(''));
  }
  return out;
}

export const HEADER = ['# Generated by generate-config-front-matter.mjs; do not edit. name, operation, input (base64 of WTF-8), result (base64 of WTF-8): JSON of the groups or `none`, the trimmed text, or the decoded or encoded units.'];

/** What the tracked file holds: `TRACKED / 2` cases from the seed. */
export const GENERATOR = Object.freeze({ script: 'generate-config-front-matter.mjs', file: FILE, header: HEADER, cases, trackedCount: TRACKED / 2, seed: SEED });

if (isMain(import.meta.url)) runGenerator(GENERATOR);
