// Build-time helpers for the static OpenCode route table. Runtime code imports
// the checked-in `opencode-routes.generated.js`, never this module; the
// generator script and the drift test share it so an SDK bump forces a
// regeneration.
import fs from 'node:fs';
import path from 'node:path';

export const OPENCODE_SDK_PACKAGE = '@opencode-ai/sdk';
export const OPENCODE_SDK_GEN_RELATIVE_PATH = path.join('dist', 'v2', 'gen', 'sdk.gen.js');
export const OPENCODE_ROUTES_GENERATED_FILENAME = 'opencode-routes.generated.js';

// Every generated operation is `(options?.client ?? this.client).<method>({ url: "…"`
// (SSE operations call `.sse.<method>(`). The plain `url:` count below catches a
// generator shape change that would otherwise drop routes silently.
const SDK_OPERATION_PATTERN = /\.(?:sse\.)?(get|post|put|patch|delete|head|options)\(\{\s*url:\s*"([^"]+)"/g;
const SDK_URL_PATTERN = /\burl:\s*"[^"]+"/g;

const compareRoutes = ([leftMethod, leftPath], [rightMethod, rightPath]) => {
  if (leftPath !== rightPath) return leftPath < rightPath ? -1 : 1;
  if (leftMethod === rightMethod) return 0;
  return leftMethod < rightMethod ? -1 : 1;
};

/** Extracts sorted, de-duplicated `[METHOD, path]` pairs from the SDK v2 generated client. */
export const extractOpenCodeSdkRoutes = (source) => {
  if (typeof source !== 'string' || source.length === 0) {
    throw new TypeError('OpenCode SDK generated source must be a non-empty string');
  }
  const operations = [...source.matchAll(SDK_OPERATION_PATTERN)];
  const urlCount = (source.match(SDK_URL_PATTERN) ?? []).length;
  if (operations.length === 0 || operations.length !== urlCount) {
    throw new Error(
      `OpenCode SDK generated client shape changed: matched ${operations.length} operations for ${urlCount} url fields; update extractOpenCodeSdkRoutes`,
    );
  }
  const routes = new Map();
  for (const [, method, routePath] of operations) {
    const upper = method.toUpperCase();
    routes.set(`${upper} ${routePath}`, [upper, routePath]);
  }
  return [...routes.values()].sort(compareRoutes);
};

/** Finds the SDK package the way Node resolves `@opencode-ai/sdk` from `startDir`. */
export const findInstalledOpenCodeSdk = (startDir) => {
  let current = path.resolve(startDir);
  for (;;) {
    const root = path.join(current, 'node_modules', ...OPENCODE_SDK_PACKAGE.split('/'));
    const manifestPath = path.join(root, 'package.json');
    if (fs.existsSync(manifestPath)) {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
      if (typeof manifest.version !== 'string' || manifest.version.length === 0) {
        throw new Error(`${manifestPath} has no version`);
      }
      return { root, version: manifest.version, genPath: path.join(root, OPENCODE_SDK_GEN_RELATIVE_PATH) };
    }
    const parent = path.dirname(current);
    if (parent === current) {
      throw new Error(`${OPENCODE_SDK_PACKAGE} is not installed above ${startDir}`);
    }
    current = parent;
  }
};

export const readOpenCodeSdkRoutes = (sdk) => ({
  version: sdk.version,
  routes: extractOpenCodeSdkRoutes(fs.readFileSync(sdk.genPath, 'utf8')),
});

export const renderOpenCodeRoutesModule = ({ version, routes }) => {
  const lines = routes.map(([method, routePath]) => `  [${JSON.stringify(method)}, ${JSON.stringify(routePath)}],`);
  return [
    `// Generated by scripts/generate-opencode-routes.mjs from ${OPENCODE_SDK_PACKAGE}@${version}`,
    `// (${OPENCODE_SDK_GEN_RELATIVE_PATH.split(path.sep).join('/')}). Do not edit by hand; rerun the script after an SDK bump.`,
    `export const OPENCODE_SDK_VERSION = ${JSON.stringify(version)};`,
    '',
    'export const OPENCODE_SDK_ROUTES = Object.freeze([',
    ...lines,
    ']);',
    '',
  ].join('\n');
};
