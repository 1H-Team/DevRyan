#!/usr/bin/env node
// Writes strings.tsv: how Node converts between strings and bytes, so
// `cargo test` (tests/strings.rs) checks JsStr::{from_utf8_lossy, to_utf8}.
// Command line: vector-tools.mjs.
//
//   decode  <bytes hex>  <code units hex>   buffer.toString('utf8')
//   encode  <code units hex>  <bytes hex>   Buffer.from(string) (lone surrogates to EF BF BD)
import { drawer, isMain, random, runGenerator, unitsHex, vectorDocument } from './vector-tools.mjs';

export const STRINGS_FILE = 'strings.tsv';
export const STRINGS_SEED = 20261115;
export const STRINGS_TRACKED = 800;

// UTF-8 fragments, valid and not: every lead class, truncations, overlongs,
// surrogates, values above U+10FFFF, stray continuations, the BOM.
const FRAGMENTS = [[0x61], [0x7f], [0x00], [0xc2, 0x80], [0xdf, 0xbf], [0xe0, 0xa0, 0x80], [0xef, 0xbf, 0xbf], [0xef, 0xbb, 0xbf], [0xf0, 0x90, 0x80, 0x80],
  [0xf4, 0x8f, 0xbf, 0xbf], [0xe2, 0x80, 0xa8], [0xc0, 0x80], [0xc1, 0xbf], [0xe0, 0x80, 0x80], [0xe0, 0x9f, 0xbf], [0xed, 0xa0, 0x80], [0xed, 0xbf, 0xbf],
  [0xf0, 0x80, 0x80, 0x80], [0xf4, 0x90, 0x80, 0x80], [0xf5, 0x80, 0x80, 0x80], [0xf8, 0x88, 0x80, 0x80, 0x80], [0xfe], [0xff], [0x80], [0xbf], [0xc2],
  [0xe2, 0x82], [0xf0, 0x9f, 0x98], [0xf0, 0x9f]];
const UNITS = [0x61, 0x00, 0x7f, 0x80, 0xff, 0x100, 0x7ff, 0x800, 0x2028, 0xfeff, 0xfffd, 0xffff, 0xd800, 0xdbff, 0xdc00, 0xdfff, 0xd83d, 0xde00];

export function renderStrings(count) {
  const d = drawer(random(STRINGS_SEED));
  const rows = [];
  for (let index = 0; index < count; index += 1) {
    const bytes = [];
    for (let at = d.int(12); at > 0; at -= 1) bytes.push(...(d.chance(0.15) ? [d.int(256)] : d.pick(FRAGMENTS)));
    const buffer = Buffer.from(bytes);
    rows.push(`decode\t${buffer.toString('hex')}\t${unitsHex(buffer.toString('utf8'))}`);
    let text = '';
    for (let at = d.int(12); at > 0; at -= 1) text += String.fromCharCode(d.chance(0.2) ? d.int(0x10000) : d.pick(UNITS));
    rows.push(`encode\t${unitsHex(text)}\t${Buffer.from(text).toString('hex')}`);
  }
  return vectorDocument(['# Generated by generate-strings.mjs; do not edit. decode: bytes, toString(utf8) units; encode: units, Buffer.from bytes.'], rows);
}

if (isMain(import.meta.url)) runGenerator({ file: STRINGS_FILE, render: renderStrings, trackedCount: STRINGS_TRACKED });
