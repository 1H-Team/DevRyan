#!/usr/bin/env node
// Writes locale-survey.tsv: for every locale Node's ICU supports, whether
// the ledger's keys sort in code-unit order under that locale's collation.
// The ledger sorts keys with localeCompare and no locale argument, so its
// order is the process default locale's; the native ledger sorts by code
// unit, so it may only be used where the two agree (DOCUMENTATION.md, "The
// locale check", lists the locales where they do not, and
// scripts/build-ledger-core.test.mjs checks that list against this file).
// The tracked file describes the runtime the app ships: run it under
// Electron's Node,
//   ELECTRON_RUN_AS_NODE=1 node_modules/electron/dist/Electron.app/Contents/MacOS/Electron \
//     packages/harness-runtime/native/ledger-core/tests/survey-locales.mjs [--check]
// Its first data row names the ICU version; Electron's ICU data holds fewer
// locales than a full-ICU Node (56 against 121 on 2026-11-12), and a locale
// without data collates as root. Under another runtime, --check fails naming
// both ICU versions; --extended <dir> writes that runtime's survey elsewhere.
//
// Locales: every two- and three-letter language code that
// Intl.Collator.supportedLocalesOf accepts, as it canonicalises them
// (`no` stays, `iw` becomes `he`, `sh` becomes `sr-Latn`), deduplicated.
// Collation variants chosen with `-u-co-` are out of scope: a default locale
// taken from LANG cannot carry one.
//
// One row per locale: locale, then `ok` or `differs` for
//   sample    the ledger key sample (ledger-key-sample.txt), the set a host sorts at start-up;
//   keys      2,902 keys of the ledger's real shapes from seeded IDs (a larger set than the sample's);
//   alphabet  the 39 characters of collate::CODE_UNIT_ORDER_SAFE alone;
// and the first two sample keys the locale orders against code units (or -).
// The generator fails if a locale passes the sample but fails the keys: the
// sample must be at least as strict as the real keys.
import { ledgerKeySample, ledgerKeys, SAFE_ALPHABET } from './generate-collate.mjs';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { TESTS_DIR, isMain, runGenerator, vectorDocument } from './vector-tools.mjs';

export const SURVEY_FILE = 'locale-survey.tsv';

const codeUnitCompare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The locales surveyed: every supported two- and three-letter language code. */
export function surveyedLocales() {
  const letters = 'abcdefghijklmnopqrstuvwxyz';
  const candidates = [];
  for (const a of letters) for (const b of letters) { candidates.push(a + b); for (const c of letters) candidates.push(a + b + c); }
  return [...new Set(Intl.Collator.supportedLocalesOf(candidates))].sort(codeUnitCompare);
}

/** The first adjacent pair that `locale` orders against code units, or null. */
function firstDisorder(sorted, collator) {
  const resorted = [...sorted].sort((a, b) => collator.compare(a, b));
  const at = resorted.findIndex((key, index) => key !== sorted[index]);
  return at < 0 ? null : [sorted[at], resorted[at]];
}

export function renderSurvey() {
  const sample = ledgerKeySample();
  const keys = ledgerKeys({ perKind: 150, groups: 60, seed: 20261118 }).sort(codeUnitCompare);
  const alphabet = [...SAFE_ALPHABET];
  const rows = [`icu\t${process.versions.icu}\t-\t-\t-`];
  for (const locale of surveyedLocales()) {
    const collator = new Intl.Collator(locale);
    const sampleDisorder = firstDisorder(sample, collator);
    const keysDiffer = firstDisorder(keys, collator) !== null;
    const alphabetDiffer = firstDisorder(alphabet, collator) !== null;
    if (keysDiffer && !sampleDisorder) throw new Error(`${locale} orders the ledger's keys against code units but passes the sample: the sample is not strict enough`);
    const verdict = (differs) => (differs ? 'differs' : 'ok');
    rows.push([locale, verdict(sampleDisorder), verdict(keysDiffer), verdict(alphabetDiffer), sampleDisorder ? sampleDisorder.join(' ') : '-'].join('\t'));
  }
  return vectorDocument(['# Generated by survey-locales.mjs; do not edit. locale, sample, keys, alphabet (ok or differs: code-unit order under that locale), first disordered sample key and the key the locale puts there.'], rows);
}

/** The locales whose collation orders the key sample against code units. */
export const refusedLocales = (text) => text.split('\n').filter((line) => line && !line.startsWith('#') && !line.startsWith('end\t'))
  .map((line) => line.split('\t')).filter((fields) => fields[1] === 'differs').map((fields) => fields[0]);

/** The ICU version a survey file was written under. */
export const surveyIcu = (text) => text.split('\n').find((line) => line.startsWith('icu\t'))?.split('\t')[1];

if (isMain(import.meta.url)) {
  const argv = process.argv.slice(2);
  if (argv.includes('--check')) {
    const tracked = readFileSync(path.join(TESTS_DIR, SURVEY_FILE), 'utf8');
    if (surveyIcu(tracked) !== process.versions.icu) {
      console.error(`${SURVEY_FILE} was written under ICU ${surveyIcu(tracked)} (Electron's Node); this is ICU ${process.versions.icu}. Run the check under Electron's Node (see the generator's header).`);
      process.exitCode = 1;
    } else runGenerator({ file: SURVEY_FILE, render: renderSurvey, trackedCount: 0, argv });
  } else if (!argv.includes('--extended') && !process.versions.electron) {
    console.error(`${SURVEY_FILE} describes Electron's runtime: write it under Electron's Node, or pass --extended <dir> for this runtime's survey.`);
    process.exitCode = 1;
  } else runGenerator({ file: SURVEY_FILE, render: renderSurvey, trackedCount: 0, argv });
}
