#!/usr/bin/env node
// Writes base64.tsv: Node's Buffer base64, both ways, so `cargo test`
// (tests/base64.rs) checks ledger_core::base64. Command line: vector-tools.mjs.
//
//   encode  <bytes hex>  buffer.toString('base64')
//   decode  <text, hex of its WTF-8>  Buffer.from(text, 'base64') as hex
//
// The decoded texts are mostly malformed on purpose: both alphabets mixed,
// whitespace, stray ASCII, `=` anywhere, missing padding, and non-ASCII code
// units chosen for their low byte (Node decodes a unit by its low byte, so
// U+0141 reads as `A` and U+D83D as `=`). src/base64.rs states the rules.
import { drawer, isMain, random, runGenerator, wtf8, vectorDocument } from './vector-tools.mjs';

export const BASE64_FILE = 'base64.tsv';
export const BASE64_SEED = 20261117;
export const BASE64_TRACKED = 3000;

const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/-_';
const OTHER = ['=', '=', '=', ' ', '\n', '\t', '\r', '\f', '\v', '!', '.', '\0', '\x7f', '\x80', '\xe9', '\xff', '\xbd', '\xc1', '\u0100', '\u0141',
  '\u013d', '\u0161', '\u2b2b', '\ud83d', '\ude00', '\u{10000}', '\uff21', '\u3d3d', '\u{1f600}', '\u2028', '\ufeff'];

export function renderBase64(count) {
  const d = drawer(random(BASE64_SEED));
  const rows = [];
  for (let index = 0; index < count; index += 1) {
    if (index % 4 === 0) {
      const bytes = Buffer.from(Array.from({ length: d.int(d.chance(0.05) ? 400 : 20) }, () => d.int(256)));
      rows.push(`encode\t${bytes.toString('hex')}\t${bytes.toString('base64')}`);
      continue;
    }
    let text;
    if (d.chance(0.25)) {
      // A valid encoding, then damaged: padding dropped, URL alphabet, whitespace, a cut.
      const encoded = Buffer.from(Array.from({ length: d.int(24) }, () => d.int(256))).toString('base64');
      const damage = d.int(5);
      text = damage === 0 ? encoded.replace(/=+$/, '') : damage === 1 ? encoded.replace(/\+/g, '-').replace(/\//g, '_')
        : damage === 2 ? encoded.replace(/(.{4})/g, '$1\n') : damage === 3 ? encoded.slice(0, d.int(encoded.length + 1)) : `${encoded}${d.pick(OTHER)}${encoded}`;
    } else {
      const length = Math.floor(d.next() ** 2 * 40);
      const mostly = d.chance(0.5) ? 0.9 : 0.6;
      text = '';
      for (let at = 0; at < length; at += 1) text += d.chance(mostly) ? LETTERS[d.int(64)] : d.pick(OTHER);
    }
    rows.push(`decode\t${wtf8(text).toString('hex')}\t${Buffer.from(text, 'base64').toString('hex')}`);
  }
  return vectorDocument(['# Generated by generate-base64.mjs; do not edit. encode: bytes, base64; decode: text (WTF-8 hex), decoded bytes.'], rows);
}

if (isMain(import.meta.url)) runGenerator({ file: BASE64_FILE, render: renderBase64, trackedCount: BASE64_TRACKED });
