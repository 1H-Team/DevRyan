#!/usr/bin/env node
// Writes sort.tsv: seeded arrays of mixed values and the order Node's
// `.sort()` (no comparator) leaves them in, so `cargo test` (tests/sort.rs)
// checks ledger_core::js::default_sort. Command line: vector-tools.mjs.
//
// One case per line: name; base64 of JSON.stringify(array) with the values
// JSON cannot hold written as null; those values as `index:kind` (u
// undefined, n NaN, i Infinity, j -Infinity), comma-separated; and the
// sorted order as original indices, comma-separated.
import { b64, drawer, isMain, powerOfTen, random, runGenerator, vectorDocument } from './vector-tools.mjs';

export const SORT_FILE = 'sort.tsv';
export const SORT_SEED = 20261116;
export const SORT_TRACKED = 500;

const SPECIAL = new Map([['u', undefined], ['n', Number.NaN], ['i', Number.POSITIVE_INFINITY], ['j', Number.NEGATIVE_INFINITY]]);
const STRINGS = ['', 'a', 'A', 'b', 'B', '10', '9', '1', '1,', '1,2', ',', 'null', 'undefined', 'true', '[object Object]', 'NaN', 'Infinity',
  '-1', '-0', '0', '1e+21', '\u00e9', 'e\u0301', '\u{1f600}', '\uff5e', '\ud800', '\udc00', '\uffff', ' ', 'a b', 'ab', 'a,b', '__proto__'];

function value(d, depth = 0) {
  const { int, pick, next } = d;
  const roll = next();
  if (roll < 0.25) return pick(STRINGS);
  if (roll < 0.5) return pick([0, -0, 1, 2, 9, 10, 11, 100, -1, -10, 1.5, 0.1, 1e21, 1e-7, 2 ** 53, -(2 ** 53), int(1000) - 500, (next() - 0.5) * powerOfTen(int(30))]);
  if (roll < 0.6) return pick([null, true, false]);
  if (roll < 0.7) return pick([...SPECIAL.keys()]);
  if (roll < 0.8 && depth < 2) return Array.from({ length: int(4) }, () => value(d, depth + 1));
  if (roll < 0.85) return {};
  return String.fromCharCode(0x20 + int(95)) + (d.chance(0.5) ? String.fromCharCode(0x20 + int(95)) : '');
}

/** A placeholder for a value JSON cannot hold. */
const marker = (kind) => ({ kind });

export function renderSort(count) {
  const d = drawer(random(SORT_SEED));
  const rows = [];
  for (let index = 0; index < count; index += 1) {
    const length = d.chance(0.1) ? d.int(200) : d.int(16);
    const specials = [];
    const items = Array.from({ length }, (_, at) => {
      if (d.chance(0.12)) { const kind = d.pick([...SPECIAL.keys()]); specials.push(`${at}:${kind}`); return marker(kind); }
      return value(d);
    });
    const live = items.map((item) => (item && typeof item === 'object' && 'kind' in item && !Array.isArray(item) ? SPECIAL.get(item.kind) : item));
    const json = JSON.stringify(items.map((item) => (item && typeof item === 'object' && 'kind' in item && !Array.isArray(item) ? null : item)));
    const order = live.map((item, at) => ({ item, at }));
    // Node's own .sort() of the values; each sorted value is then mapped back
    // to the first unused original position holding that very value (arrays
    // and objects by reference), which is where a stable sort took it from.
    const sorted = order.map(({ item }) => item).sort();
    const used = new Set();
    const permutation = sorted.map((item) => {
      const found = order.findIndex((entry, at) => !used.has(at) && Object.is(entry.item, item));
      used.add(found);
      return found;
    });
    rows.push(`sort-${index}\t${b64(Buffer.from(json, 'utf8'))}\t${specials.join(',')}\t${permutation.join(',')}`);
  }
  return vectorDocument(['# Generated by generate-sort.mjs; do not edit. name, JSON (base64), index:kind of undefined/NaN/Infinity, sorted original indices.'], rows);
}

if (isMain(import.meta.url)) runGenerator({ file: SORT_FILE, render: renderSort, trackedCount: SORT_TRACKED });
