#!/usr/bin/env node
// Writes numbers.tsv: seeded doubles and Node's String(x), so `cargo test`
// (tests/numbers.rs) checks ledger_core::js::number_to_string against V8's
// Number::toString. Command line: vector-tools.mjs.
//
// One case per line: the double's 64 bits (hex, big-endian) and String(x).
// The doubles: random bit patterns over every exponent, subnormals, integers
// around 2^53, values near the 1e21 and 1e-7 layout boundaries, short decimals
// (few significant digits, the shapes records hold), exact halfway ties
// between two shortest candidates, and their neighbours one ulp away.
import { drawer, isMain, random, runGenerator, vectorDocument } from './vector-tools.mjs';

export const NUMBERS_FILE = 'numbers.tsv';
export const NUMBERS_SEED = 20261114;
export const NUMBERS_TRACKED = 5000;

const view = new DataView(new ArrayBuffer(8));
const bitsOf = (x) => { view.setFloat64(0, x); return view.getBigUint64(0); };
const fromBits = (bits) => { view.setBigUint64(0, bits); return view.getFloat64(0); };
const hexBits = (x) => bitsOf(x).toString(16).padStart(16, '0');

export function numberCases(count) {
  const d = drawer(random(NUMBERS_SEED));
  const { int, pick, chance, next } = d;
  const out = [0, -0, 1, -1, 1e21, 1e20, 999999999999999900000, 1e-7, 1e-6, 1.5e-7, 9.999999999999999e-7, 123e-20, 5e-324, -5e-324,
    2.2250738585072014e-308, 2.225073858507201e-308, Number.MAX_VALUE, Number.MIN_VALUE, Number.EPSILON, 2 ** 53, 2 ** 53 + 2, 2 ** 53 - 1,
    0.1 + 0.2, 1000000000000042.25, 83176082636972.125, 0.5, 2.5, 1.25, 1e300, 1e-300, 123456789012345680000, 4294967295, 4294967296];
  const randomBits = () => (BigInt(Math.floor(next() * 2 ** 32)) << 32n) | BigInt(Math.floor(next() * 2 ** 32));
  while (out.length < count) {
    const roll = next();
    let x;
    if (roll < 0.35) x = fromBits(randomBits());
    else if (roll < 0.45) x = fromBits(randomBits() & 0x800fffffffffffffn); // subnormal
    else if (roll < 0.55) x = (chance(0.5) ? -1 : 1) * (2 ** 53 + int(2001) - 1000) * (chance(0.2) ? 2 ** int(20) : 1);
    else if (roll < 0.7) x = (1 + (next() - 0.5) * 10 ** -int(17)) * 10 ** pick([-8, -7, -6, -5, 15, 16, 17, 20, 21, 22]);
    else if (roll < 0.85) x = Number(`${int(10 ** (1 + int(9)))}e${int(60) - 30}`); // short decimals
    else {
      // An exact dyadic tie: an integer plus j/2^m with few fractional bits,
      // at magnitudes where it needs 17 digits.
      const m = 1 + int(8);
      x = Math.floor(next() * 10 ** (16 - Math.ceil(m * 0.30103))) + (2 * int(2 ** (m - 1)) + 1) / 2 ** m;
    }
    if (!Number.isFinite(x)) continue;
    out.push(x);
    if (chance(0.1)) { const bits = bitsOf(x); for (const neighbour of [bits - 1n, bits + 1n]) if (neighbour >= 0n && neighbour < 0x7ff0000000000000n) out.push(fromBits(neighbour)); }
  }
  return out.slice(0, count);
}

export function renderNumbers(count) {
  const rows = numberCases(count).map((x) => `${hexBits(x)}\t${String(x)}`);
  return vectorDocument(['# Generated by generate-numbers.mjs; do not edit. 64 bits of the double (hex), Node String(x).'], rows);
}

if (isMain(import.meta.url)) runGenerator({ file: NUMBERS_FILE, render: renderNumbers, trackedCount: NUMBERS_TRACKED });
